"""
Tool implementations for Autonomous Financial & Business Intelligence Agent.
These functions are exposed as callable tools for the agent.
"""

import os
import pandas as pd

DATA_PATH = os.path.join(os.path.dirname(__file__), "data", "sales_records.csv")

def load_data() -> pd.DataFrame:
    """Loads the financial dataset and computes derived fields."""
    if not os.path.exists(DATA_PATH):
        raise FileNotFoundError(f"Dataset not found at {DATA_PATH}")
    df = pd.read_csv(DATA_PATH)
    df["Revenue"] = df["Quantity"] * df["Unit_Price"]
    df["Total_Cost"] = df["Quantity"] * df["Unit_Cost"]
    df["Gross_Profit"] = df["Revenue"] - df["Total_Cost"]
    df["Profit_Margin_%"] = ((df["Gross_Profit"] / df["Revenue"]) * 100).round(2)
    return df

def get_dataset_summary() -> str:
    """Returns the schema, date range, and high-level structure of the dataset."""
    df = load_data()
    summary = f"""
Dataset Summary:
- Total Transactions: {len(df)}
- Columns: {list(df.columns)}
- Date Range: {df['Date'].min()} to {df['Date'].max()}
- Regions: {list(df['Region'].unique())}
- Categories: {list(df['Category'].unique())}
- Products: {list(df['Product_Name'].unique())}
"""
    return summary.strip()

def calculate_kpis() -> dict:
    """Calculates overall business financial KPIs."""
    df = load_data()
    total_rev = float(df["Revenue"].sum())
    total_cost = float(df["Total_Cost"].sum())
    total_profit = float(df["Gross_Profit"].sum())
    margin = round((total_profit / total_rev) * 100, 2)
    top_product = df.groupby("Product_Name")["Revenue"].sum().idxmax()
    top_region = df.groupby("Region")["Revenue"].sum().idxmax()

    return {
        "Total_Revenue": f"${total_rev:,.2f}",
        "Total_Cost": f"${total_cost:,.2f}",
        "Gross_Profit": f"${total_profit:,.2f}",
        "Overall_Profit_Margin": f"{margin}%",
        "Top_Revenue_Product": top_product,
        "Top_Revenue_Region": top_region
    }

def analyze_by_dimension(dimension: str) -> str:
    """
    Aggregates financial performance by a given dimension.
    Supported dimensions: 'Product_Name', 'Region', 'Category'
    """
    valid_dims = ["Product_Name", "Region", "Category"]
    if dimension not in valid_dims:
        return f"Error: Invalid dimension '{dimension}'. Choose from: {valid_dims}"

    df = load_data()
    grouped = df.groupby(dimension).agg(
        Total_Units=("Quantity", "sum"),
        Total_Revenue=("Revenue", "sum"),
        Total_Profit=("Gross_Profit", "sum")
    ).reset_index()

    grouped["Profit_Margin_%"] = ((grouped["Total_Profit"] / grouped["Total_Revenue"]) * 100).round(2)
    grouped = grouped.sort_values(by="Total_Revenue", ascending=False)
    try:
        return grouped.to_markdown(index=False)
    except (ImportError, Exception):
        return grouped.to_string(index=False)

def export_executive_report(report_title: str, report_body: str) -> str:
    """Saves a generated executive summary report to a markdown file."""
    output_dir = os.path.join(os.path.dirname(__file__), "reports")
    os.makedirs(output_dir, exist_ok=True)
    filename = f"{report_title.lower().replace(' ', '_')}.md"
    file_path = os.path.join(output_dir, filename)

    content = f"# {report_title}\n\n*Generated by Autonomous Financial Agent*\n\n{report_body}"
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(content)
    return f"Report successfully saved to: reports/{filename}"
